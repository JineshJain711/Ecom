const mongoose = require('mongoose');

const orderSchema = new mongoose.Schema({
    user:{
        type:mongoose.Schema.Types.ObjectId,
        required:true,
        ref:'User'
    },
    items:[
        {
            product:{
                type:mongoose.Schema.Types.ObjectId,    
            required:true,
            ref:'Product'
            },
            quantity:{
                type:Number,
                required:true,
                min:1
            },
            price:{
                type:Number,
                required:true
            }
        }],
    totalPrice:{
        type:Number,
        required:true
    },
    shippingAddress:{
            fullName:{
                type:String,
                required:true
            },
            street:{
                type:String,
                required:true
            },
            city:{
                type:String,
                required:true   
            },
            postalCode:{
                type:String,
                required:true
            },
            country:{
                type:String,
                required:true
            }
    },
    paymentId:{
        type:String,
        required:true
    },

    status:{
        type:String,
        enum:['pending','shipped','delivered'],
        default:'pending'
    },
    createdAt:{
        type:Date,
        default:Date.now
    }
},{
    timestamps:true
});

module.exports = mongoose.model('Order', orderSchema);